function readYoutubeApiKey(): string | undefined {
  const fromMeta = (import.meta.env as Record<string, string | undefined>).YOUTUBE_API_KEY;
  if (fromMeta) return fromMeta;
  if (typeof process !== 'undefined') return process.env.YOUTUBE_API_KEY;
  return undefined;
}

async function fetchYoutubeSnippet(videoId: string): Promise<{ title: string; description: string } | null> {
  const apiKey = readYoutubeApiKey();
  if (!apiKey) return null;
  try {
    const res = await fetch(
      `https://www.googleapis.com/youtube/v3/videos?part=snippet&id=${encodeURIComponent(videoId)}&key=${apiKey}`,
    );
    if (!res.ok) return null;
    const json = (await res.json()) as { items?: { snippet?: { title?: string; description?: string } }[] };
    const snippet = json.items?.[0]?.snippet;
    if (!snippet) return null;
    return { title: snippet.title ?? '', description: snippet.description ?? '' };
  } catch {
    return null;
  }
}

const packs = (manifest as { packs: GalleryImagePack[] }).packs;

function packToPublicItem(p: GalleryImagePack): PublicGalleryItem {
  const largest = p.variants[p.variants.length - 1]!;
  return {
    kind: 'media',
    url: largest.webpUrl,
    packId: p.id,
    image: {
      width: p.width,
      height: p.height,
      lqip: p.lqip,
      variants: p.variants.map((v) => ({ w: v.w, avif: v.avifUrl, webp: v.webpUrl })),
      exif: p.exif ?? null,
      ...(p.col !== undefined ? { col: p.col } : {}),
    },
  };
}

