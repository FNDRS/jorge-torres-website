/**
 * Static gallery sourced from public/media/visuals (generated by scripts/build-visuals-manifest.mjs)
 * plus EMBEDS and LOCAL_VIDEOS. YouTube title/description are fetched once at build time (this page
 * is prerendered) via the YouTube Data API; silently omitted if YOUTUBE_API_KEY isn't configured.
 */
export async function resolveGalleryItems(): Promise<PublicGalleryItem[]> {
  const sortedEmbeds = [...EMBEDS].sort((a, b) => new Date(b.addedAt).getTime() - new Date(a.addedAt).getTime());

  const embedItems: PublicGalleryItem[] = await Promise.all(
    sortedEmbeds.map(async (e): Promise<PublicGalleryItem> => {
      if (e.provider !== 'youtube') return { kind: 'vimeo', videoId: e.videoId };
      const snippet = await fetchYoutubeSnippet(e.videoId);
      return {
        kind: 'youtube',
        videoId: e.videoId,
        ...(snippet?.title ? { title: snippet.title } : {}),
        ...(snippet?.description ? { description: snippet.description } : {}),
        ...(e.embeddable === false ? { embeddable: false } : {}),
      };
    }),
  );

  const localVideoItems: PublicGalleryItem[] = LOCAL_VIDEOS.map((v) => ({
    kind: 'media',
    url: v.url,
    title: v.title,
    description: v.description,
    ...(v.thumb ? { thumb: v.thumb } : {}),
  }));

  // Videos (YouTube embeds + local) appear at the end; photos first
  return [...packs.map(packToPublicItem), ...localVideoItems, ...embedItems];
}
