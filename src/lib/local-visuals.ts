export type GalleryImagePack = {
  id: string;
  uploadedAt: string;
  width: number;
  height: number;
  lqip: string;
  variants: GalleryImageVariant[];
  exif?: GalleryImageExif | null;
  col?: number; // explicit column (0-based) set by admin reorder; overrides packing algorithm
};

export type PublicGalleryImageMeta = {
  width: number;
  height: number;
  lqip: string;
  variants: { w: number; avif: string; webp: string }[];
  exif?: GalleryImageExif | null;
  col?: number;
};

export type PublicGalleryItem =
  | { kind: 'media'; url: string; packId?: string; image?: PublicGalleryImageMeta; title?: string; description?: string; thumb?: string }
  | { kind: 'youtube'; videoId: string; title?: string; description?: string; embeddable?: boolean }
  | { kind: 'vimeo'; videoId: string };

